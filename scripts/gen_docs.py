#!/usr/bin/env python3
"""
Generate the docs pages and site data that are copies of the contract and its records.

    python scripts/gen_docs.py           # write the files
    python scripts/gen_docs.py --check   # exit 1 if any file differs from what would be written

A method cannot exist in the code and be missing from the docs, and the judge
prompt on the site cannot drift from the one validators read, because both are
written from contracts/triage.py by this script, and a test runs --check.

Writes:
  web/content/docs/reference/contract.mdx    every public method, from the source
  web/content/docs/reference/errors.mdx      every refusal sentence, from the source
  web/content/docs/reference/addresses.mdx   the deployment, from contracts/FROZEN.json
  web/content/docs/more/judge-prompt.mdx     the judge prompt, word for word
  web/content/docs/more/evaluation.mdx       the golden run, from eval/results.json
  web/content/docs/more/limitations.mdx      every limit the contract enforces, from the source
  web/lib/contract.generated.json            limits and the prompt, for the site
and refreshes every `{/* include: path */}` code sample in the docs from the file it names.
"""

from __future__ import annotations

import ast
import hashlib
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONTRACT = ROOT / "contracts" / "triage.py"
DOCS = ROOT / "web" / "content" / "docs"
REPO = "https://github.com/meitipro/triage/blob/main"

HEADER = "{/* Generated by scripts/gen_docs.py from contracts/triage.py. Do not edit by hand. */}\n\n"


def load():
    source = CONTRACT.read_text(encoding="utf-8")
    return source, ast.parse(source)


def constant(tree: ast.Module, name: str):
    for node in tree.body:
        if isinstance(node, ast.Assign) and ast.unparse(node.targets[0]) == name:
            try:
                return ast.literal_eval(node.value)
            except ValueError:
                return ast.unparse(node.value)
    raise KeyError(name)


def contract_class(tree: ast.Module) -> ast.ClassDef:
    return next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == "Triage")


def kind_of(node: ast.FunctionDef) -> str:
    for deco in node.decorator_list:
        text = ast.unparse(deco)
        if text == "gl.public.write":
            return "write"
        if text == "gl.public.write.payable":
            return "payable"
        if text == "gl.public.view":
            return "view"
    return ""


def mdx_text(text: str) -> str:
    """Plain prose into MDX: braces and angle brackets would be read as code."""
    return text.replace("{", "&#123;").replace("}", "&#125;").replace("<", "&lt;").replace(">", "&gt;")


def signature(node: ast.FunctionDef) -> str:
    args = ", ".join(f"{a.arg}: {ast.unparse(a.annotation)}" for a in node.args.args[1:])
    returns = ast.unparse(node.returns) if node.returns else "None"
    return f"{node.name}({args}) -> {returns}"


def methods(tree: ast.Module) -> list[dict]:
    out = []
    for node in contract_class(tree).body:
        if isinstance(node, ast.FunctionDef) and kind_of(node):
            doc = ast.get_docstring(node) or ""
            out.append(
                {
                    "name": node.name,
                    "kind": kind_of(node),
                    "signature": signature(node),
                    "args": [{"name": a.arg, "type": ast.unparse(a.annotation)} for a in node.args.args[1:]],
                    "returns": ast.unparse(node.returns) if node.returns else "None",
                    "doc": " ".join(doc.split()),
                    "line": node.lineno,
                }
            )
    return out


def refusals(tree: ast.Module) -> list[dict]:
    """Every UserError sentence, with the function it can come from. Dynamic parts read as '…'."""

    def text_of(expr: ast.AST) -> tuple[str, str]:
        parts: list[str] = []

        def walk(e: ast.AST) -> None:
            if isinstance(e, ast.BinOp) and isinstance(e.op, ast.Add):
                walk(e.left)
                walk(e.right)
            elif isinstance(e, ast.Constant) and isinstance(e.value, str):
                parts.append(e.value)
            elif isinstance(e, ast.Name) and e.id in ("E", "L"):
                parts.append("\x00" + e.id)
            else:
                parts.append("…")

        walk(expr)
        prefix = parts[0][1:] if parts and parts[0].startswith("\x00") else ""
        body = "".join(p for p in parts if not p.startswith("\x00"))
        return prefix, body

    owner: dict[int, str] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef):
            for inner in ast.walk(node):
                if hasattr(inner, "lineno"):
                    owner.setdefault(inner.lineno, node.name)
    rows: dict[tuple, dict] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and ast.unparse(node.func) == "gl.vm.UserError" and node.args:
            prefix, body = text_of(node.args[0])
            key = (prefix, body)
            where = owner.get(node.lineno, "")
            row = rows.setdefault(key, {"prefix": prefix, "text": body, "where": []})
            if where and where not in row["where"]:
                row["where"].append(where)
    return sorted(rows.values(), key=lambda r: (r["prefix"], r["text"]))


