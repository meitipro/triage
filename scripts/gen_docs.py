        "---",
        "",
        HEADER.strip(),
        "",
        "## Honest limits",
        "",
        "- **Actionable, not important.** Triage decides whether a report is worth acting on, not how important it is. "
        "Every actionable report earns the same reward; severity stays with the team, through bonuses.",
